package shapes

// Shape — общий интерфейс для всех геометрических фигур.
// Любая структура, реализующая эти четыре метода, автоматически
// удовлетворяет интерфейсу Shape (утиная типизация в Go).
type Shape interface {
	// Area возвращает площадь фигуры.
	Area() float64

	// Perimeter возвращает периметр (длину границы) фигуры.
	Perimeter() float64

	// String реализует интерфейс fmt.Stringer для красивого вывода.
	String() string

	// Type возвращает строковое имя типа фигуры (например, "Circle").
	Type() string
}
