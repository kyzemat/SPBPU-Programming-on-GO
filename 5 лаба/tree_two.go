package main

// ============================================================
// ЗАДАЧА 6: Same Tree (Одинаковые деревья)
// ============================================================
// Два дерева одинаковы, если они структурно идентичны и значения
// в соответствующих узлах равны. Решение: рекурсивный обход (DFS).

// IsSameTree проверяет, что деревья p и q совпадают по форме и значениям.
func IsSameTree(p, q *TreeNode) bool {
	// Оба пусты — поддеревья совпадают.
	if p == nil && q == nil {
		return true
	}
	// Пусто только одно из них — формы различаются.
	if p == nil || q == nil {
		return false
	}
	// Значения должны совпасть, а также левые и правые поддеревья.
	return p.Val == q.Val &&
		IsSameTree(p.Left, q.Left) &&
		IsSameTree(p.Right, q.Right)
}
